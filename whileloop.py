# 1 to 100 using loop
i = 1
while i <= 100: 
    print(i)
    i += 1

print ('end of loop')


# 100 to 1 using loop
j = 100 
while j >= 1:
    print(j)
    j -= 1

print("end of loop 2")


# multiplication table using loop 

n = int(input('enter a number'))
m = 1 
while m <= 10:
    print(n*m)
    m += 1
print('end of table')


