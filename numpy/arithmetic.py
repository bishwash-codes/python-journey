import numpy

array = numpy.array([1, 2, 3, 4, 5])

# scalar

print(array + 10)
print(array - -5)
print(array * 3)
print(array**2)
print(array / 2)


# element operations

array1 = numpy.array([2, 3, 4, 5, 6])
array2 = numpy.array([1, 2, 4, 5, 7])

print(array1 - array2)
print(array1 + array2)
print(array1**array2)
print(array1 * array2)
